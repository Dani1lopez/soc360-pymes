#!/usr/bin/env python3
"""Prepare the local .env that docker-compose.app.yml needs.

Creates .env from .env.example when it does not exist yet, then fills in the
values that must never be shared or committed: the application secret, the lock
secret, and the two passwords the product stack uses.

The product stack deliberately ships no default credential, so this step is the
difference between "one command" and "one command with a secret baked into the
repository".

Properties that matter:
  * Idempotent. An existing non-empty value is never overwritten, so running it
    again after editing .env changes nothing.
  * A quoted empty value (``KEY=""``) counts as empty and is filled.
  * An ``export`` prefix survives, so ``source .env`` keeps working.
  * The file is created with owner-only permissions, because it holds secrets.
  * Values are never printed and never passed as command-line arguments, so
    nothing leaks into the terminal scrollback or into ``ps`` output.

Usage:
    ./scripts/demo_bootstrap.py
"""

from __future__ import annotations

import re
import secrets
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
ENV_FILE = ROOT / ".env"
EXAMPLE_FILE = ROOT / ".env.example"

# Keys that must hold a generated value: without them the application either
# refuses to start or the stack would share a credential.
FILL_IF_EMPTY = (
    "SECRET_KEY",
    "LOCK_KEY_SECRET",
    "POSTGRES_PASSWORD",
    "APP_DB_PASSWORD",
    "APP_REDIS_PASSWORD",
)

# The settings validator requires a key with this prefix whenever the LLM
# provider is Groq, even with enrichment disabled. The product stack keeps
# enrichment off, so this placeholder is never sent to any provider.
GROQ_PLACEHOLDER = "gsk_demo_placeholder_enrichment_disabled"

SECTION_HEADER = "# Generated by scripts/demo_bootstrap.py for the product stack."

# Owner read/write only: the file holds secrets.
ENV_FILE_MODE = 0o600

_ASSIGNMENT = re.compile(
    r"^(?P<prefix>\s*(?:export\s+)?)"
    r"(?P<name>[A-Za-z_][A-Za-z0-9_]*)"
    r"\s*=\s*"
    r"(?P<value>.*)$"
)


def _token(nbytes: int) -> str:
    return secrets.token_urlsafe(nbytes)


def _generate(key: str) -> str:
    """Return a fresh value for ``key``, sized for what consumes it."""
    if key == "SECRET_KEY":
        # 96 bytes become 128 urlsafe characters: exactly the minimum length the
        # settings validator accepts, with far more entropy than the 3.0
        # bits/char it also requires.
        return _token(96)
    if key == "LOCK_KEY_SECRET":
        return _token(48)
    return _token(24)


def _bare_value(raw: str) -> str:
    """Return the value as its consumer would read it: unquoted, without comment."""
    value = raw.split(" #", 1)[0].strip()
    if len(value) >= 2 and value[0] == value[-1] and value[0] in {"'", '"'}:
        return value[1:-1]
    return value


def _assignment(line: str) -> tuple[str, str, str] | None:
    """Split a ``KEY=value`` line, ignoring comments and blanks."""
    match = _ASSIGNMENT.match(line)
    if match is None:
        return None
    return match.group("prefix"), match.group("name"), match.group("value")


def main() -> int:
    if not EXAMPLE_FILE.exists():
        print(f"error: {EXAMPLE_FILE.name} not found", file=sys.stderr)
        return 1

    if ENV_FILE.exists():
        lines = ENV_FILE.read_text(encoding="utf-8").splitlines()
        origin = ENV_FILE.name
    else:
        lines = EXAMPLE_FILE.read_text(encoding="utf-8").splitlines()
        origin = EXAMPLE_FILE.name

    seen: set[str] = set()
    filled: list[str] = []

    for index, line in enumerate(lines):
        parsed = _assignment(line)
        if parsed is None:
            continue
        prefix, name, raw = parsed
        seen.add(name)
        if _bare_value(raw):
            continue
        if name in FILL_IF_EMPTY:
            lines[index] = f"{prefix}{name}={_generate(name)}"
            filled.append(name)
        elif name == "GROQ_API_KEY":
            lines[index] = f"{prefix}{name}={GROQ_PLACEHOLDER}"
            filled.append(name)

    missing = [key for key in FILL_IF_EMPTY if key not in seen]
    if missing:
        lines.extend(["", SECTION_HEADER])
        for key in missing:
            lines.append(f"{key}={_generate(key)}")
            filled.append(key)

    ENV_FILE.write_text("\n".join(lines) + "\n", encoding="utf-8")
    ENV_FILE.chmod(ENV_FILE_MODE)

    print(f"{origin} -> {ENV_FILE.name}")
    if filled:
        print("Values filled: " + ", ".join(filled))
    else:
        print("Nothing to fill: every required value was already set.")
    print("No value is shown above, and none was passed as an argument.")
    print()
    print("Next: docker compose -f docker-compose.app.yml up --build")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
